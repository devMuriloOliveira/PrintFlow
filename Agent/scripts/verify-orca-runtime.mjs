import { access, mkdtemp, readFile, rm } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { discoverStoreOrcaPath } from '../src/slicing/orcaRuntime.js'
import { buildOfficialBambuP1SProfile, listOfficialOrcaPrinterModels, resolveOfficialOrcaProfileForPrinter } from '../src/slicing/orcaProfiles.js'
import { sliceWithOrcaSlicer } from '../src/slicing/orcaSlicer.js'

const root = fileURLToPath(new URL('../', import.meta.url))

try {
  // Only the official Store-signed identity: no unsigned/global fallback in install validation.
  const executablePath = discoverStoreOrcaPath()
  if (!executablePath) throw new Error('OrcaSlicer oficial Microsoft Store nao encontrado na versao validada.')
  for (const model of listOfficialOrcaPrinterModels()) {
    const profile = resolveOfficialOrcaProfileForPrinter({ printer: { manufacturer: 'Bambu Lab', model: model.replace(/^bambu lab /, '') }, executablePath })
    await Promise.all([...profile.settingsPaths, ...profile.filamentPaths].map(file => access(file)))
  }
  const temporaryRoot = await mkdtemp(path.join(os.tmpdir(), 'printflow-orca-install-check-'))
  try {
    const artifact = await sliceWithOrcaSlicer({
      executablePath,
      inputPath: path.join(root, 'assets/slicing-smoke-cube.stl'),
      outputPath: path.join(temporaryRoot, 'cube.gcode'),
      profile: buildOfficialBambuP1SProfile({ executablePath }),
      timeoutMs: 120000
    })
    const gcode = await readFile(artifact.outputPath, 'utf8')
    if (!/^G[01]\s/m.test(gcode) || !/^M10[49]\s/m.test(gcode)) throw new Error('G-code de teste nao contem movimentos e aquecimento esperados.')
    if (!/generated by OrcaSlicer 2\.4\.2\b/.test(gcode)) throw new Error('Motor OrcaSlicer difere da versao 2.4.2 validada.')
    console.log(JSON.stringify({ ok: true, channel: 'Microsoft Store', version: '2.4.2', sizeBytes: artifact.sizeBytes, sha256: artifact.sha256 }))
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true })
  }
} catch (error) {
  console.error(`OrcaSlicer oficial Store nao passou no fatiamento local: ${error.message}`)
  process.exitCode = 1
}
